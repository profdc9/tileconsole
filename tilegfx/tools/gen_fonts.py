"""Turn the Unscii .hex fonts into C source for tilegfx.

    python3 -I tools/gen_fonts.py <unscii fontfiles directory> fonts

Only the public-domain variants are converted (never unscii-16-full, which is GPL). Each font becomes its own .c file
so that a program links only the fonts it uses. Glyphs are stored one byte per row, most significant bit leftmost, and
codepoints as runs of consecutive values.
"""
import hashlib
import os
import re
import sys

# (hex file, C name, cell height in pixels)
FONTS = [
    ("unscii-8", "unscii8", 8),
    ("unscii-8-alt", "unscii8_alt", 8),
    ("unscii-8-thin", "unscii8_thin", 8),
    ("unscii-8-tall", "unscii8_tall", 16),
    ("unscii-8-fantasy", "unscii8_fantasy", 8),
    ("unscii-8-mcr", "unscii8_mcr", 8),
    ("unscii-16", "unscii16", 16),
]
LINE = re.compile(r"([0-9A-Fa-f]{4,6}):([0-9A-Fa-f]+)")


def parse(path, height):
    """Return ([(codepoint, bytes)], number of glyphs skipped, why)."""
    glyphs, skipped = [], 0
    with open(path, encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            m = LINE.fullmatch(line)
            if not m:
                raise SystemExit("%s: malformed line %r" % (path, line))
            cp, data = int(m.group(1), 16), bytes.fromhex(m.group(2))
            if len(data) == height:
                glyphs.append((cp, data))
            elif height == 8 and len(data) == 16 and not any(data):
                glyphs.append((cp, data[:8]))   # a blank 16-byte placeholder (U+0000) in an 8x8 font
            elif height == 16 and len(data) == 32:
                skipped += 1                    # a double-width (16x16) glyph: not representable in an 8-pixel cell
            else:
                raise SystemExit("%s: unexpected glyph size %d for U+%04X" % (path, len(data), cp))
    glyphs.sort()
    cps = [cp for cp, _ in glyphs]
    assert len(set(cps)) == len(cps)
    return glyphs, skipped


def runs_of(glyphs):
    runs = []   # (first codepoint, count, index of the first glyph)
    for i, (cp, _) in enumerate(glyphs):
        if runs and runs[-1][0] + runs[-1][1] == cp:
            runs[-1][1] += 1
        else:
            runs.append([cp, 1, i])
    return runs


def emit(src_dir, out_dir, hexname, cname, height):
    path = os.path.join(src_dir, hexname + ".hex")
    with open(path, "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    glyphs, skipped = parse(path, height)
    runs = runs_of(glyphs)
    assert all(count < 65536 and idx < 65536 for _, count, idx in runs)
    out = ['/* SPDX-License-Identifier: CC0-1.0 */',
           '/* Generated by tools/gen_fonts.py from %s.hex (Unscii, public domain / CC0; see fonts/FONTS.md). Do not edit. */' % hexname,
           '#include "tg_font.h"', '']
    out.append("static const tg_glyph_run_t runs[%d] = {" % len(runs))
    for first, count, idx in runs:
        out.append("    {0x%X, %d, %d}," % (first, count, idx))
    out += ["};", ""]
    out.append("static const uint8_t glyphs[%d] = {" % (len(glyphs) * height))
    for cp, data in glyphs:
        out.append("    " + ",".join("0x%02X" % b for b in data) + ",  /* U+%04X */" % cp)
    out += ["};", ""]
    out.append("const tg_font_t tg_font_%s = {runs, %d, %d, glyphs, %d};" % (cname, len(runs), len(glyphs), height))
    with open(os.path.join(out_dir, cname + ".c"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    return hexname, cname, height, len(glyphs), len(runs), skipped, sha


def main():
    src_dir, out_dir = sys.argv[1], sys.argv[2]
    rows = [emit(src_dir, out_dir, *font) for font in FONTS]
    for hexname, cname, height, n, nruns, skipped, sha in rows:
        print("%-18s tg_font_%-16s 8x%-2d  %4d glyphs in %3d runs, %3d wide glyphs skipped  sha256 %s" %
              (hexname + ".hex", cname, height, n, nruns, skipped, sha))


main()
